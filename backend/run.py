"""Точка входа для запуска из PyCharm (или просто `python run.py`).

Обычный способ запуска — `uvicorn app.main:app --reload` в терминале — это
консольная команда, а не .py-файл, поэтому конфигурации PyCharm типа
"Python script" с ней не работают напрямую (или требуют настройки через
"Module name", что менее очевидно для новичка). Этот файл — просто
Python-скрипт, который делает то же самое программно: PyCharm может
запустить его кнопкой ▶ Run как обычный .py-файл.

Важно: рабочая директория (Working directory) в настройках конфигурации
запуска должна быть указана как папка `backend/` (а не `money-apk/` целиком)
— иначе Python не найдёт локальный пакет `app/`.

host="0.0.0.0" (а не "127.0.0.1") — иначе сервер слушает только loopback и
не примет соединение от Android-эмулятора: тот обращается через виртуальный
адрес 10.0.2.2, и для хоста это выглядит как соединение "снаружи", а не с
самой машины. При этом `curl http://127.0.0.1:8000/health` с самого Mac
как работал, так и будет работать — 0.0.0.0 слушает все интерфейсы, включая
loopback.
"""

import uvicorn

if __name__ == "__main__":
    uvicorn.run("app.main:app", host="0.0.0.0", port=8000, reload=True)
